import { readFile, writeFile } from 'node:fs/promises';
import ts from 'typescript';
const root = new URL('../', import.meta.url);
let output = '// GENERATED by npm run build:apps-script. Edit lib/impact/core.ts, config.ts or apps-script/adapter.js instead.\n';
for (const path of ['lib/impact/config.ts', 'lib/impact/core.ts']) {
  const source = (await readFile(new URL(path, root), 'utf8')).replace(/^import .*;\r?\n/gm, '').replace(/^export /gm, '');
  output += ts.transpileModule(source, {compilerOptions:{target:ts.ScriptTarget.ES2020,module:ts.ModuleKind.None}}).outputText + '\n';
}
output += await readFile(new URL('apps-script/adapter.js',root), 'utf8');
await writeFile(new URL('apps-script/Code.gs',root), output);
console.log('Generated apps-script/Code.gs from the shared campaign engine.');
